function buildRuleIndex(rules) {
  // rules: [[keyword, category, priority], ...]
  const indexed = rules.map(([kw, cat, prio]) => [String(kw).toLowerCase(), cat, prio]);
  indexed.sort((a, b) => b[2] - a[2]);
  return indexed;
}

function classify(counterparty, description, rules) {
  const text = `${counterparty || ""} ${description || ""}`.toLowerCase();
  if (!text.trim()) return "未分类";
  for (const [kw, cat] of rules) {
    if (text.includes(kw)) return cat;
  }
  return "未分类";
}

